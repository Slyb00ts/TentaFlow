/// Whether a process with this name runs right now, read from `/proc`. Needed
/// for `nfsd`, which is a kernel thread with no pid file and no unit name that
/// is the same on every distribution.
pub fn process_running(name: &str) -> bool {
    let Ok(entries) = std::fs::read_dir("/proc") else {
        return false;
    };
    for entry in entries.flatten() {
        let file = entry.file_name();
        let Some(pid) = file.to_str() else { continue };
        if !pid.bytes().all(|b| b.is_ascii_digit()) {
            continue;
        }
        if let Ok(comm) = std::fs::read_to_string(entry.path().join("comm")) {
            if comm.trim() == name {
                return true;
            }
        }
    }
    false
}

/// The two protocol services as the Sharing tab shows them.
pub async fn services(db: &DbPool) -> Vec<NasShareService> {
    let env = super::environment::cached_or_probe(db).await.ok();
    let feature = |id: &str| {
        env.as_ref()
            .and_then(|e| e.features.iter().find(|f| f.id == id).cloned())
    };
    let smb = feature("samba");
    let nfs = feature("nfs");
    vec![
        NasShareService {
            protocol: "smb".to_string(),
            installed: smb.as_ref().is_some_and(|f| f.status == "ok"),
            running: process_running("smbd"),
            version: smb.as_ref().and_then(|f| f.version.clone()),
            config_path: tentanas_helper::SMB_INCLUDE_PATH.to_string(),
            detail: smb.map(|f| f.detail).unwrap_or_default(),
        },
        NasShareService {
            protocol: "nfs".to_string(),
            installed: nfs.as_ref().is_some_and(|f| f.status == "ok"),
            running: process_running("nfsd"),
            version: nfs.as_ref().and_then(|f| f.version.clone()),
            config_path: tentanas_helper::NFS_EXPORTS_PATH.to_string(),
            detail: nfs.map(|f| f.detail).unwrap_or_default(),
        },
    ]
}

fn service_installed(protocol: &str) -> bool {
    match protocol {
        "smb" => super::environment::find_binary("smbd").is_some(),
        _ => super::environment::find_binary("exportfs").is_some(),
    }
}

/// What a share's `state`/`state_detail` are right now, without touching the
/// system: disabled by the admin, broken for a reason the UI can act on, or
/// active. The reason is what decides whether the share reaches the generated
/// config at all.
///
/// `installed` answers "does this node have that protocol's server", passed in
/// so the whole verdict is decided by arguments rather than by the host the
/// function happens to run on. `smb_direct_refusal` is the node's ksmbd
/// verdict (§5.4b) when it cannot serve SMB Direct: a share that asked for it
/// stays ACTIVE — Samba keeps exporting it over the LAN, which is most of what
/// it is for — but carries the reason, so the UI shows a warning instead of
/// the option looking as if it took effect.
pub fn share_state(
    share: &ShareRow,
    source: &Result<Source>,
    installed: &dyn Fn(&str) -> bool,
    smb_direct_refusal: Option<&str>,
) -> (&'static str, String) {
    if !share.enabled {
        return ("disabled", String::new());
    }
    match source {
        Err(e) => ("error", e.to_string()),
        Ok(s) if !s.mounted => (
            "error",
            "source path is not mounted — the share stays out of the config".to_string(),
        ),
        Ok(_) => {
            if !installed(&share.protocol) {
                let missing = if share.protocol == "smb" {
                    "samba missing"
                } else {
                    "nfs-kernel-server missing"
                };
                return ("error", missing.to_string());
            }
            // A fleet mount is always served over NFS, whatever the share's
            // own protocol is — see fleet_mounts.rs.
            if share.fleet_mount && !installed("nfs") {
                return ("error", "nfs-kernel-server missing".to_string());
            }
            match smb_direct_refusal.filter(|_| super::ksmbd::smb_direct(share)) {
                Some(reason) => ("active", reason.to_string()),
                None => ("active", String::new()),
            }
        }
    }
}

