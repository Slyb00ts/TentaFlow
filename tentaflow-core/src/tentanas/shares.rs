/// The header of the app-owned include file. It is a comment, so smbd ignores
/// it, and it tells an admin reading `/etc/samba/tentanas.conf` by hand that
/// editing it is pointless — the next share change overwrites the file.
const SMB_HEADER: &str = "# Generated by TentaNas. Every section below is rebuilt from the app's\n\
                          # database on every share change; edits here are lost.\n";

fn line(out: &mut String, key: &str, value: &str) {
    out.push('\t');
    out.push_str(key);
    out.push_str(" = ");
    out.push_str(value);
    out.push('\n');
}

/// The share section of one SMB share. `read only = no` plus explicit
/// `write list`/`read list` is what makes the per-user grants decide, and the
/// masks match the setgid share root `ShareChown` creates.
pub fn smb_section(share: &ShareRow) -> String {
    let smb = share.smb.clone().unwrap_or_default();
    let mut out = format!("[{}]\n", share.name);
    line(&mut out, "path", &share.source_path);
    line(&mut out, "browseable", "yes");
    line(&mut out, "read only", "no");
    line(&mut out, "guest ok", if smb.guests { "yes" } else { "no" });
    if smb.guests {
        // A guest connection maps to a user outside the share group, so the
        // group has to be forced for the files it creates to stay shared.
        line(&mut out, "force group", tentanas_helper::SHARE_GROUP);
    }
    let names: Vec<&str> = smb.users.iter().map(|u| u.user.as_str()).collect();
    if !names.is_empty() {
        line(&mut out, "valid users", &names.join(", "));
        let write: Vec<&str> = smb
            .users
            .iter()
            .filter(|u| u.mode == "rw")
            .map(|u| u.user.as_str())
            .collect();
        let read: Vec<&str> = smb
            .users
            .iter()
            .filter(|u| u.mode != "rw")
            .map(|u| u.user.as_str())
            .collect();
        if !write.is_empty() {
            line(&mut out, "write list", &write.join(", "));
        }
        if !read.is_empty() {
            line(&mut out, "read list", &read.join(", "));
        }
    }
    line(&mut out, "create mask", "0660");
    line(&mut out, "directory mask", "2770");

    // vfs_fruit must load before streams_xattr, and catia is what makes the
    // illegal-character mapping fruit expects work.
    let mut vfs: Vec<&str> = Vec::new();
    if smb.time_machine {
        vfs.extend(["catia", "fruit", "streams_xattr"]);
    }
    if smb.previous_versions {
        vfs.push("shadow_copy2");
    }
    if smb.recycle_bin {
        vfs.push("recycle");
    }
    if !vfs.is_empty() {
        line(&mut out, "vfs objects", &vfs.join(" "));
    }
    if smb.previous_versions {
        // ZFS exposes its snapshots under `.zfs/snapshot`, and the app names
        // them `auto-<YYYYMMDD>-<HHMM>-<tier>` / `manual-<YYYYMMDD>-<HHMMSS>`
        // in NODE LOCAL time. snapprefix + delimiter split that prefix off so
        // one format matches both; a snapshot named by hand outside those two
        // shapes is simply not offered as a previous version.
        line(&mut out, "shadow:snapdir", ".zfs/snapshot");
        line(&mut out, "shadow:sort", "desc");
        line(&mut out, "shadow:localtime", "yes");
        line(&mut out, "shadow:snapprefix", "^(auto|manual)$");
        line(&mut out, "shadow:delimiter", "-");
        line(&mut out, "shadow:format", "%Y%m%d-%H%M");
    }
    if smb.recycle_bin {
        line(&mut out, "recycle:repository", ".recycle/%U");
        line(&mut out, "recycle:keeptree", "yes");
        line(&mut out, "recycle:versions", "yes");
        line(&mut out, "recycle:touch", "yes");
    }
    if smb.time_machine {
        line(&mut out, "fruit:time machine", "yes");
        line(&mut out, "fruit:metadata", "stream");
        line(&mut out, "fruit:model", "RackMac");
    }
    out
}

/// The whole app-owned include file for the shares that are actually
/// exportable right now.
///
/// `ksmbd_interfaces` is the listener split of §5.4b: when the second SMB
/// backend takes the node's RDMA interfaces, Samba has to stop binding them or
/// the two servers fight over TCP 445 — whichever starts first wins and the
/// other silently serves nothing. Samba's `interfaces` has no exclusion
/// syntax, so the `[global]` block names everything ksmbd did NOT take. An
/// empty list means ksmbd is not running and smbd keeps its own defaults.
pub fn smb_document(shares: &[ShareRow], ksmbd_interfaces: &[String]) -> String {
    let mut out = SMB_HEADER.to_string();
    if !ksmbd_interfaces.is_empty() {
        let keep = super::ksmbd::samba_interfaces_here(ksmbd_interfaces);
        out.push('\n');
        out.push_str("[global]\n");
        line(&mut out, "interfaces", &keep.join(" "));
        line(&mut out, "bind interfaces only", "yes");
    }
    for share in shares.iter().filter(|s| s.protocol == "smb") {
        out.push('\n');
        out.push_str(&smb_section(share));
    }
    out
}

