/// Connected SMB clients per share name, from `smbstatus --json`. A tree
/// connect is what the UI calls a session: one client attached to one share.
pub fn parse_smbstatus(text: &str) -> BTreeMap<String, Vec<NasShareSession>> {
    let mut out: BTreeMap<String, Vec<NasShareSession>> = BTreeMap::new();
    let Ok(doc) = serde_json::from_str::<Value>(text) else {
        return out;
    };
    let sessions = doc.get("sessions").and_then(Value::as_object);
    let user_of = |session_id: Option<&str>| -> String {
        session_id
            .and_then(|id| sessions?.get(id))
            .and_then(|s| s.get("username"))
            .and_then(Value::as_str)
            .unwrap_or_default()
            .to_string()
    };
    let Some(tcons) = doc.get("tcons").and_then(Value::as_object) else {
        return out;
    };
    for tcon in tcons.values() {
        let Some(service) = tcon.get("service").and_then(Value::as_str) else {
            continue;
        };
        // IPC$ is Samba's own named-pipe tree, not a share anybody configured.
        if service == "IPC$" {
            continue;
        }
        out.entry(service.to_string())
            .or_default()
            .push(NasShareSession {
                client: tcon
                    .get("machine")
                    .and_then(Value::as_str)
                    .unwrap_or_default()
                    .to_string(),
                user: user_of(tcon.get("session_id").and_then(Value::as_str)),
                connected_at: tcon
                    .get("connected_at")
                    .and_then(Value::as_str)
                    .map(str::to_string),
            });
    }
    out
}

/// One `/proc/fs/nfsd/clients/<id>/info` document.
pub fn parse_nfs_client_info(text: &str) -> Option<NasShareSession> {
    let mut address = None;
    let mut name = None;
    for line in text.lines() {
        let Some((key, value)) = line.split_once(':') else {
            continue;
        };
        let value = value.trim().trim_matches('"').to_string();
        match key.trim() {
            "address" => address = Some(value),
            "name" => name = Some(value),
            _ => {}
        }
    }
    Some(NasShareSession {
        client: address?,
        user: name.unwrap_or_default(),
        connected_at: None,
    })
}

/// Every NFSv4 client the kernel currently holds state for. NFSv4 state is
/// per CLIENT, not per export, so this is the same list for every NFS share of
/// the node — there is no per-export session to report.
pub fn nfs_clients() -> Vec<NasShareSession> {
    let Ok(entries) = std::fs::read_dir("/proc/fs/nfsd/clients") else {
        return Vec::new();
    };
    entries
        .flatten()
        .filter_map(|e| std::fs::read_to_string(e.path().join("info")).ok())
        .filter_map(|text| parse_nfs_client_info(&text))
        .collect()
}

/// Sessions of one share. SMB needs root (Samba's tdb files), NFS does not.
pub async fn sessions(db: &DbPool, share: &ShareRow) -> Vec<NasShareSession> {
    if share.protocol == "nfs" {
        return nfs_clients();
    }
    let Ok((out, _)) = super::broker::run_privileged(
        db,
        &HelperCommand::SmbStatus {},
        None,
        Duration::from_secs(30),
    )
    .await
    else {
        return Vec::new();
    };
    if !out.success() {
        return Vec::new();
    }
    parse_smbstatus(&out.stdout)
        .remove(&share.name)
        .unwrap_or_default()
}

/// Session COUNTS for the whole list view: one `smbstatus` call for every SMB
/// share instead of one per row.
pub async fn session_counts(db: &DbPool, shares: &[ShareRow]) -> BTreeMap<String, u32> {
    let mut out = BTreeMap::new();
    if shares.iter().any(|s| s.protocol == "smb") {
        if let Ok((result, _)) = super::broker::run_privileged(
            db,
            &HelperCommand::SmbStatus {},
            None,
            Duration::from_secs(30),
        )
        .await
        {
            if result.success() {
                for (name, list) in parse_smbstatus(&result.stdout) {
                    out.insert(name, list.len() as u32);
                }
            }
        }
    }
    if shares.iter().any(|s| s.protocol == "nfs") {
        let clients = nfs_clients().len() as u32;
        for share in shares.iter().filter(|s| s.protocol == "nfs") {
            out.insert(share.name.clone(), clients);
        }
    }
    out
}

