/// The share source browser. An empty `path` lists the pool mountpoints; any
/// other path must be one of them or below it, so the browser can never walk
/// out of the pools.
pub async fn browse(db: &DbPool, path: &str) -> Result<(String, Vec<NasDirEntry>)> {
    let datasets = super::datasets::list("").await.map_err(|e| anyhow!("{e}"))?;
    let shares = store::list_shares(db)?;
    let shared_as = |p: &str| -> Vec<String> {
        shares
            .iter()
            .filter(|s| s.source_path == p)
            .map(|s| s.name.clone())
            .collect()
    };
    let dataset_at = |p: &str| -> Option<String> {
        datasets
            .iter()
            .find(|d| d.mountpoint.as_deref() == Some(p))
            .map(|d| d.name.clone())
    };
    if path.is_empty() {
        let entries = datasets
            .iter()
            .filter(|d| !d.name.contains('/'))
            .filter_map(|d| d.mountpoint.as_ref().map(|m| (d, m)))
            .map(|(d, mountpoint)| NasDirEntry {
                name: d.name.clone(),
                dataset: Some(d.name.clone()),
                shared_as: shared_as(mountpoint),
                path: mountpoint.clone(),
            })
            .collect();
        return Ok((String::new(), entries));
    }
    let source = resolve_source(&datasets, path)?;
    let mut entries = Vec::new();
    for entry in std::fs::read_dir(&source.path)
        .map_err(|e| anyhow!("'{}' cannot be listed: {e}", source.path))?
        .flatten()
    {
        // Only real directories: a symlink here would be a way to browse (and
        // then export) something outside the pools.
        if !entry.file_type().is_ok_and(|t| t.is_dir()) {
            continue;
        }
        let name = entry.file_name().to_string_lossy().into_owned();
        if name.starts_with('.') {
            continue;
        }
        let child = format!("{}/{name}", source.path.trim_end_matches('/'));
        entries.push(NasDirEntry {
            dataset: dataset_at(&child),
            shared_as: shared_as(&child),
            path: child,
            name,
        });
    }
    entries.sort_by(|a, b| a.name.cmp(&b.name));
    Ok((source.path, entries))
}

