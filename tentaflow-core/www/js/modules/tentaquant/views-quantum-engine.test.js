import { window } from './_test-setup.js';
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const gluePath = fileURLToPath(new URL('../../quantum/quantum_glue.js', import.meta.url));
const wasmPath = fileURLToPath(new URL('../../quantum/quantum_glue_bg.wasm', import.meta.url));
const missing = [gluePath, wasmPath].filter((path) => !existsSync(path));
const skip = missing.length
  ? `the wasm glue is not built (${missing.join(', ')}); run \`cargo check\` in tentaflow-core `
    + 'with the wasm32-unknown-unknown target and wasm-bindgen-cli installed'
  : false;
const options = skip ? { skip } : {};

// `_test-setup.js` answers every fetch that is not a locale with an empty body,
// which is exactly the state `available()` reports as "this build has no
// simulator". These screens are watched against the engine itself, so the
// quantum glue's own `file:` URL is served from disk here — and only that one,
// so every other module keeps the load path the rest of the view tests use.
if (!skip) {
  const served = globalThis.fetch;
  const wasmUrl = new URL('../../quantum/quantum_glue_bg.wasm', import.meta.url).href;
  globalThis.fetch = (url, init) => {
    if (String(url) !== wasmUrl) return served(url, init);
    return Promise.resolve(new Response(readFileSync(wasmPath), {
      headers: { 'content-type': 'application/wasm' },
    }));
  };
}

const { drawStudio, studioState } = await import('./studio.js');
const { drawNotebook } = await import('./notebook.js');
const { createCell, serializeCells, updateCell } = await import('./cells.js');
const { COUNTS_MIME, STATE_MIME, totalShots } = await import('./quantum-view.js');

/// A two-qubit program with NO classical register: it has a state and cannot be
/// sampled, which is the pair of properties every case here turns on.
const UNITARY = 'OPENQASM 3.0;\ninclude "stdgates.inc";\n\nqubit[2] q;\n\nh q[0];\ncx q[0], q[1];\n';

const CELLS = [
  createCell('markdown', { id: 'm1', source: '# Splątanie\n' }),
  createCell('circuit', { id: 'c1' }),
];

function fakeScreen(over = {}) {
  const root = window.document.createElement('div');
  root.className = 'tq-root';
  window.document.body.appendChild(root);
  return {
    root,
    instanceId: 'tentaquant-0a1b2c3d',
    projectId: 'splatanie',
    project: {
      projectId: 'splatanie', name: 'Splątanie', myRole: 'owner', archivedAt: null,
    },
    projectTab: 'studio',
    notebooks: [{ notebookId: 'nb1', name: 'Splątanie', currentVersion: 3, updatedAt: '2026-09-03 14:02:00' }],
    files: [],
    notebookId: 'nb1',
    studio: studioState(),
    projectViewDispose: null,
    reloadFiles() {},
    reloadNotebooks() {},
    openStudioWithCell() {},
    userId: 'u1',
    lab: { instanceId: 'tentaquant-0a1b2c3d', displayName: 'Kwanty R&D', nodes: [], myPermissions: ['quant.read', 'quant.run'] },
    openRun() {},
    tq(kind) {
      // Every case here runs in the BROWSER, so the auto rule answers T0 and
      // the target list carries only the tier that needs no node.
      if (kind === 'tentaQuantTargetListRequest') {
        return Promise.resolve({
          targets: [{
            target: 'browser', tier: 'T0', nodeId: null, nodeName: 'browser', isLocal: true,
            online: true, available: true, maxQubits: 24, precision: 'single', reason: null,
          }],
        });
      }
      if (kind === 'tentaQuantTargetResolveRequest') {
        return Promise.resolve({ target: 'browser', tier: 'T0', nodeId: null, reason: 'fits the browser', unavailable: [] });
      }
      if (kind === 'tentaQuantNotebookGetRequest') {
        return Promise.resolve({
          notebook: { notebookId: 'nb1', name: 'Splątanie', currentVersion: 3, updatedAt: '2026-09-03 14:02:00' },
          version: 3,
          cellsJson: serializeCells(CELLS),
        });
      }
      return Promise.resolve({});
    },
    ...over,
  };
}

const cleanup = () => { window.document.body.innerHTML = ''; };

/// Records what `files.js::downloadText` hands the browser — the blob it built
/// and the name on the anchor it clicked — and answers the restore function.
function captureDownloads(into) {
  const anchors = window.HTMLAnchorElement.prototype;
  const realClick = anchors.click;
  const realCreate = URL.createObjectURL;
  const realRevoke = URL.revokeObjectURL;
  let pending = null;
  URL.createObjectURL = (blob) => { pending = blob; return 'blob:tentaquant-test'; };
  URL.revokeObjectURL = () => {};
  anchors.click = function click() { into.push({ name: this.download, type: pending?.type, blob: pending }); };
  return () => {
    anchors.click = realClick;
    URL.createObjectURL = realCreate;
    URL.revokeObjectURL = realRevoke;
  };
}

async function until(predicate, what) {
  for (let attempt = 0; attempt < 400; attempt += 1) {
    const value = predicate();
    if (value) return value;
    await new Promise((resolve) => setTimeout(resolve, 5));
  }
  throw new Error(`timed out waiting for ${what}`);
}

function mountStudio(over = {}) {
  const screen = fakeScreen(over);
  const host = window.document.createElement('div');
  screen.root.appendChild(host);
  return { screen, host, view: drawStudio(screen, host) };
}

