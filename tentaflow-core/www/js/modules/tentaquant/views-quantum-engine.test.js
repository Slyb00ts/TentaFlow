async function mountNotebook() {
  const screen = fakeScreen({ projectTab: 'notebook' });
  const host = window.document.createElement('div');
  screen.root.appendChild(host);
  const view = drawNotebook(screen, host);
  await view.mount();
  return { screen, host, view };
}

/// Types `source` into a cell's OpenQASM tab exactly as the editor reports it.
function typeInto(view, id, source) {
  const editor = view.cellEl(id).querySelector('[data-editor]');
  editor.value = source;
  editor.dispatchEvent(new window.CustomEvent('change', {
    bubbles: true,
    detail: { value: source, dirty: true },
  }));
}

test('a circuit cell with no classical register runs for its state, not for counts', options, async () => {
  const { host, view } = await mountNotebook();
  const id = view.cells.find((c) => c.kind === 'circuit').id;
  view.cells = updateCell(view.cells, id, { source: UNITARY });
  view.render();
  await view.run(id);

  const box = view.cellEl(id).querySelector('[data-out]');
  assert.equal(box.querySelector('[data-counts]'), null, 'no histogram of nothing');
  assert.match(box.textContent, /pomiar/, 'the cell says why there are no counts');
  const state = box.querySelector('[data-state]');
  assert.ok(state.bundle[STATE_MIME], 'the state is what such a cell answers with');
  assert.equal(state.bundle[STATE_MIME].numQubits, 2);
  assert.equal(state.bundle[STATE_MIME].amplitudes.length, 8, 'two qubits is eight numbers');
  assert.doesNotMatch(box.textContent, /shot/, 'and the head does not count shots it never drew');
  assert.ok(host.contains(box));
  cleanup();
});

test('a measured cell still runs for its counts', options, async () => {
  const { view } = await mountNotebook();
  const id = view.cells.find((c) => c.kind === 'circuit').id;
  await view.run(id);
  const counts = view.cellEl(id).querySelector('[data-out] [data-counts]');
  assert.ok(counts.bundle[COUNTS_MIME], 'the default cell measures, so it counts');
  assert.equal(totalShots(counts.bundle[COUNTS_MIME].counts), counts.bundle[COUNTS_MIME].shots);
  cleanup();
});

test('a text edit of the last circuit cell moves the state panel with it', options, async () => {
  const { host, view } = await mountNotebook();
  const id = view.cells.find((c) => c.kind === 'circuit').id;
  const hint = () => host.querySelector('#tq-nb-panel-hint');
  // The cell as it starts: a program that ends in a measurement has no single
  // state vector, and the panel says exactly that.
  await until(() => hint() && /pomiar/.test(hint().textContent), 'the panel to answer the measured cell');
  assert.equal(host.querySelectorAll('#tq-nb-bloch tf-bloch-sphere').length, 0);

  typeInto(view, id, UNITARY);
  await until(
    () => host.querySelector('#tq-nb-amps')?.bundle?.[STATE_MIME],
    'the panel to follow the edited program',
  );
  assert.equal(host.querySelectorAll('#tq-nb-bloch tf-bloch-sphere').length, 2);
  assert.match(view.cells.find((c) => c.id === id).source, /cx q\[0\], q\[1\];/);
  cleanup();
});
