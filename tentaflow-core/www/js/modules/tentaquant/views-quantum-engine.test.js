// Q07 — a circuit that cannot be sampled
// ---------------------------------------------------------------------------

test('the Studio refuses a run it cannot sample and keeps the state panel', options, async () => {
  const { host, view } = mountStudio({ studio: studioState({ source: UNITARY }) });
  await until(() => view.circuit && view.sim, 'the parsed circuit and its register');
  // The panel needs no shots, so it answers this circuit in full.
  assert.ok(host.querySelector('#tq-studio-amps').bundle[STATE_MIME], 'the amplitudes are there');
  assert.equal(host.querySelectorAll('#tq-studio-bloch tf-bloch-sphere').length, 2);

  await view.run();
  const counts = host.querySelector('#tq-studio-counts');
  assert.equal(counts.bundle[COUNTS_MIME], undefined, 'no histogram of nothing');
  assert.match(counts.bundle['text/plain'], /pomiar/, 'the slot says why, in the user’s language');
  assert.equal(view.counts, null);
  // The refusal is the screen's, not the engine's: nothing failed, so the
  // status banner stays empty and the panel is untouched.
  assert.equal(host.querySelector('#tq-studio-status').innerHTML, '');
  assert.ok(host.querySelector('#tq-studio-amps').bundle[STATE_MIME]);
  cleanup();
});

test('a measured circuit still fills the histogram', options, async () => {
  const { host, view } = mountStudio();
  await until(() => view.circuit && view.sim, 'the default Bell circuit');
  view.state.shots = 512;
  await view.run();
  const counts = host.querySelector('#tq-studio-counts');
  assert.ok(counts.bundle[COUNTS_MIME], 'the histogram is a counts bundle');
  assert.equal(counts.bundle[COUNTS_MIME].shots, 512);
  assert.equal(totalShots(view.counts), 512);
  cleanup();
});

test('the Studio exports the circuit as a Qiskit program', options, async () => {
  const { host, view } = mountStudio({ studio: studioState({ name: 'Splątanie ĄĆŻ', source: UNITARY }) });
  await until(() => view.circuit, 'the parsed circuit');
  // The real save path is watched, not a stubbed method: `downloadText` mints a
  // blob URL and clicks an anchor, and both halves are what has to be right.
  const files = [];
  const saved = captureDownloads(files);
  try {
    host.querySelector('[data-act="export-qiskit"]')
      .dispatchEvent(new window.MouseEvent('click', { bubbles: true }));
    await until(() => files.length, 'the exported program');
  } finally {
    saved();
  }
  assert.equal(files[0].name, 'splatanie-acz.py');
  assert.equal(files[0].type, 'text/x-python;charset=utf-8');
  const text = await files[0].blob.text();
  assert.match(text, /^from qiskit import QuantumCircuit, QuantumRegister, ClassicalRegister$/m);
  assert.match(text, /^circuit\.cx\(q\[0\], q\[1\]\)$/m);
  cleanup();
});

